import React from 'react';
import {beforeEach,it,expect,vi} from 'vitest';
import {render,screen,fireEvent,waitFor,within} from '@testing-library/react';
import InvoiceEntryForm from './InvoiceEntryForm';
import {nfeXml,makeKey} from '../testFixtures/nfe';
const api=vi.hoisted(()=>({post:vi.fn(),get:vi.fn()}));
vi.mock('../services/api',()=>({default:api}));
const item={_id:'11111111-1111-1111-1111-111111111111',nome:'Coca lata',unidade:'UN',ativo:true};
beforeEach(()=>{vi.clearAllMocks();vi.spyOn(window,'confirm').mockReturnValue(true);api.post.mockResolvedValue({data:{}});api.get.mockResolvedValue({data:[]});});
async function upload(xml=nfeXml()){
 const file=new File([xml],'nfe.xml',{type:'application/xml'}),bytes=new TextEncoder().encode(xml);
 file.arrayBuffer=async()=>bytes.buffer;
 fireEvent.change(screen.getByLabelText('Arquivo XML da NF-e'),{target:{files:[file]}});
 await screen.findByText('NF-e 1 / Série 1');
}
it('recognizes saved parties by document while preserving the original XML names',async()=>{
 api.get.mockImplementation(path=>Promise.resolve({data:path==='/fornecedores'?[{_id:'s',nome:'Nome do cadastro',documento:'12.345.678/0001-95',ativo:true}]:[]}));
 render(<InvoiceEntryForm items={[item]} onClose={vi.fn()} onSuccess={vi.fn()}/>);await upload();
 expect(await screen.findByText('Fornecedor reconhecido: Nome do cadastro')).toBeInTheDocument();
 expect(screen.getByLabelText('Nome / razão social do fornecedor')).toHaveValue('Fornecedor & Bebidas');
 expect(screen.getByLabelText('Nome / razão social do fornecedor')).toHaveAttribute('readonly');
});
it('does not import stock when the final confirmation is declined',async()=>{
 window.confirm.mockReturnValue(false);
 render(<InvoiceEntryForm items={[item]} onClose={vi.fn()} onSuccess={vi.fn()}/>);
 await upload();
 expect(screen.getByLabelText('Valor total da nota')).toHaveValue(96);
 expect(screen.getByLabelText('Soma dos itens lançados')).toHaveValue(96);
 expect(screen.getByLabelText('Diferença (nota − total calculado)')).toHaveValue(0);
 fireEvent.change(screen.getByLabelText('Insumo do item 1'),{target:{value:item._id}});
 fireEvent.click(screen.getByRole('button',{name:'Registrar entrada da NF-e'}));
 expect(api.post).not.toHaveBeenCalled();
 expect(screen.getByLabelText('Insumo do item 1')).toHaveValue(item._id);
});
it('links an invoice product and converts two packages into 24 units with a safe retry',async()=>{
 api.post.mockRejectedValueOnce(new Error('Resposta perdida'));
 const success=vi.fn();render(<InvoiceEntryForm items={[item]} onClose={vi.fn()} onSuccess={success}/>);
 await upload();
 fireEvent.change(screen.getByLabelText('Insumo do item 1'),{target:{value:item._id}});
 fireEvent.change(screen.getByLabelText('Unidades por embalagem do item 1'),{target:{value:'12'}});
 expect(screen.getByText('Entrada do item 1: 24 UN')).toBeInTheDocument();
 fireEvent.click(screen.getByRole('button',{name:'Registrar entrada da NF-e'}));
 expect(await screen.findByRole('alert')).toHaveTextContent('Resposta perdida');
 fireEvent.click(screen.getByRole('button',{name:'Registrar entrada da NF-e'}));
 await waitFor(()=>expect(api.post).toHaveBeenCalledTimes(2));
 expect(api.post.mock.calls[0][1]).toMatchObject({xml:nfeXml(),lines:[{line:1,stockItemId:item._id,quantity:'2',factor:'12'}]});
 expect(api.post.mock.calls[0][1].requestId).toBe(api.post.mock.calls[1][1].requestId);
 expect(success).toHaveBeenCalled();
});
it('keeps invoice quantity separate from adjusted received quantity',async()=>{
 render(<InvoiceEntryForm items={[item]} onClose={vi.fn()} onSuccess={vi.fn()}/>);await upload();
 fireEvent.change(screen.getByLabelText('Insumo do item 1'),{target:{value:item._id}});
 fireEvent.change(screen.getByLabelText('Quantidade recebida do item 1'),{target:{value:'1'}});
 fireEvent.change(screen.getByLabelText('Unidades por embalagem do item 1'),{target:{value:'12'}});
 expect(screen.getByText('Entrada do item 1: 12 UN')).toBeInTheDocument();
 fireEvent.click(screen.getByRole('button',{name:'Registrar entrada da NF-e'}));
 await waitFor(()=>expect(api.post).toHaveBeenCalledWith('/entradas-nfe',expect.objectContaining({xml:nfeXml(),lines:[expect.objectContaining({quantity:'1'})]})));
});
it('offers the official portal and rejects XML for a different typed key',async()=>{
 render(<InvoiceEntryForm items={[item]} onClose={vi.fn()} onSuccess={vi.fn()}/>);
 expect(screen.getByRole('link',{name:'Abrir portal oficial'})).toHaveAttribute('href','https://www.nfe.fazenda.gov.br/portal/consultaRecaptcha.aspx');
 fireEvent.change(screen.getByLabelText('Chave de acesso (44 dígitos)'),{target:{value:makeKey(2)}});
 const bytes=new TextEncoder().encode(nfeXml()),file=new File([nfeXml()],'nfe.xml');file.arrayBuffer=async()=>bytes.buffer;
 fireEvent.change(screen.getByLabelText('Arquivo XML da NF-e'),{target:{files:[file]}});
 expect(await screen.findByRole('alert')).toHaveTextContent('outra chave');
 expect(api.post).not.toHaveBeenCalled();
});
it('creates and selects an insumo without losing invoice links, quantities or notes',async()=>{
 const created={_id:'22222222-2222-2222-2222-222222222222',nome:'Novo refrigerante',unidade:'UN',ativo:true};
 api.post.mockResolvedValueOnce({data:created});
 render(<InvoiceEntryForm items={[item]} onClose={vi.fn()} onSuccess={vi.fn()}/>);await upload(nfeXml({items:2}));
 fireEvent.change(screen.getByLabelText('Insumo do item 1'),{target:{value:item._id}});
 fireEvent.change(screen.getByLabelText('Unidades por embalagem do item 1'),{target:{value:'12'}});
 fireEvent.change(screen.getByLabelText('Quantidade recebida do item 2'),{target:{value:'3'}});
 fireEvent.change(screen.getByLabelText('Unidades por embalagem do item 2'),{target:{value:'6'}});
 fireEvent.change(screen.getByLabelText('Observações da entrada'),{target:{value:'Recebimento parcial'}});
 const date=screen.getByLabelText('Data de entrada').value;
 fireEvent.click(screen.getByRole('button',{name:'Novo insumo para o item 2'}));
 const editor=screen.getByRole('dialog',{name:'Novo item'});await waitFor(()=>expect(within(editor).getByRole('button',{name:'Salvar item'})).toBeEnabled());
 expect(within(editor).getByLabelText('Nome do item')).toHaveValue('Coca-Cola pacote 2');
 fireEvent.change(within(editor).getByLabelText('Nome do item'),{target:{value:created.nome}});
 fireEvent.click(within(editor).getByRole('button',{name:'Salvar item'}));
 await waitFor(()=>expect(screen.queryByRole('dialog',{name:'Novo item'})).not.toBeInTheDocument());
 expect(screen.getByLabelText('Insumo do item 2')).toHaveValue(created._id);
 expect(screen.getByLabelText('Insumo do item 1')).toHaveValue(item._id);
 expect(screen.getByLabelText('Observações da entrada')).toHaveValue('Recebimento parcial');
 expect(screen.getByLabelText('Data de entrada')).toHaveValue(date);
 expect(screen.getByText('Entrada do item 2: 18 UN')).toBeInTheDocument();
 fireEvent.click(screen.getByRole('button',{name:'Registrar entrada da NF-e'}));
 await waitFor(()=>expect(api.post).toHaveBeenCalledWith('/entradas-nfe',expect.objectContaining({lines:[expect.objectContaining({stockItemId:item._id,factor:'12'}),expect.objectContaining({stockItemId:created._id,quantity:'3',factor:'6'})]})));
});
it('keeps the imported invoice when insumo creation fails or is canceled',async()=>{
 api.post.mockRejectedValueOnce(new Error('Falha ao cadastrar'));
 render(<InvoiceEntryForm items={[]} onClose={vi.fn()} onSuccess={vi.fn()}/>);await upload();
 fireEvent.click(screen.getByRole('button',{name:'Novo insumo para o item 1'}));
 const editor=screen.getByRole('dialog',{name:'Novo item'});await waitFor(()=>expect(within(editor).getByRole('button',{name:'Salvar item'})).toBeEnabled());
 fireEvent.click(within(editor).getByRole('button',{name:'Salvar item'}));
 expect(await within(editor).findByRole('alert')).toHaveTextContent('Falha ao cadastrar');
 fireEvent.click(within(editor).getByRole('button',{name:'Cancelar'}));
 expect(screen.getByText('NF-e 1 / Série 1')).toBeInTheDocument();
 expect(screen.queryByRole('dialog',{name:'Novo item'})).not.toBeInTheDocument();
 expect(screen.getByLabelText('Insumo do item 1')).toHaveValue('');
});
it('prefills supplier data from the issuer and preserves the invoice while saving',async()=>{
 const supplier={_id:'s1',nome:'Fornecedor & Bebidas',documento:'12345678000195',ativo:true};
 api.post.mockResolvedValueOnce({data:supplier});
 const xml=nfeXml().replace('</emit>','<xFant>Bebidas Bahia</xFant><IE>123456</IE><enderEmit><xLgr>Rua das Bebidas</xLgr><nro>10</nro><xBairro>Centro</xBairro><xMun>Salvador</xMun><UF>BA</UF><CEP>40000000</CEP><fone>7133334444</fone></enderEmit></emit>');
 render(<InvoiceEntryForm items={[item]} onClose={vi.fn()} onSuccess={vi.fn()}/>);await upload(xml);
 fireEvent.change(screen.getByLabelText('Insumo do item 1'),{target:{value:item._id}});
 fireEvent.change(screen.getByLabelText('Unidades por embalagem do item 1'),{target:{value:'12'}});
 fireEvent.change(screen.getByLabelText('Observações da entrada'),{target:{value:'Nota recebida'}});
 fireEvent.click(screen.getByRole('button',{name:'Cadastrar fornecedor da NF-e'}));
 const editor=await screen.findByRole('dialog',{name:'Novo fornecedor'});
 expect(within(editor).getByLabelText('Nome / razão social')).toHaveValue(supplier.nome);
 expect(within(editor).getByLabelText('CPF / CNPJ')).toHaveValue('12.345.678/0001-95');
 expect(within(editor).getByLabelText('Nome fantasia')).toHaveValue('Bebidas Bahia');
 expect(within(editor).getByLabelText('Telefone')).toHaveValue('(71) 3333-4444');
 expect(within(editor).getByLabelText('Endereço')).toHaveValue('Rua das Bebidas, 10, Centro, Salvador / BA, CEP 40000000');
 expect(within(editor).getByLabelText('Observações')).toHaveValue('Inscrição estadual: 123456');
 fireEvent.click(within(editor).getByRole('button',{name:'Salvar fornecedor'}));
 await screen.findByText('Fornecedor cadastrado: '+supplier.nome);
 expect(screen.getByLabelText('Insumo do item 1')).toHaveValue(item._id);
 expect(screen.getByLabelText('Observações da entrada')).toHaveValue('Nota recebida');
 expect(screen.getByText('Entrada do item 1: 24 UN')).toBeInTheDocument();
 expect(api.post).toHaveBeenCalledWith('/fornecedores',expect.objectContaining({documento:supplier.documento,nomeFantasia:'Bebidas Bahia'}));
});
it('recognizes a supplier already registered with a formatted document',async()=>{
 api.get.mockResolvedValue({data:[{nome:'Fornecedor existente',documento:'12.345.678/0001-95',ativo:true}]});
 render(<InvoiceEntryForm items={[item]} onClose={vi.fn()} onSuccess={vi.fn()}/>);await upload();
 fireEvent.click(screen.getByRole('button',{name:'Cadastrar fornecedor da NF-e'}));
 await screen.findByText('Fornecedor já cadastrado: Fornecedor existente');
 expect(screen.queryByRole('dialog',{name:'Novo fornecedor'})).not.toBeInTheDocument();
 expect(api.post).not.toHaveBeenCalled();
});
